// Using another project's nodes, without a symlink and without hand-copied stubs.
//
// Cascade discovers a project's nodes by listing `nodes/<name>/index.ts` and
// reads each definition from that file's own syntax tree; it never executes a
// module and never follows a re-export to find one. So a node borrowed from
// another project still needs a file here that spells its definition out. What
// goes wrong is keeping that copy by hand: cloud-shared's consumers each
// carried copied stubs and a script to catch them drifting.
//
// This writes the stubs instead. The provider project is an ordinary
// dependency (`"cloud-shared": "file:../cloud-shared"` in package.json, then
// `npm install`), and for each borrowed node this generates
//
//   nodes/<name>/index.ts
//     import type { NodeDefinition } from 'cascade/contracts';
//     export const definition = { …copied verbatim from the provider… };
//     export { execute } from '../../node_modules/<provider>/nodes/<name>/index';
//
// The execute import is a relative path on purpose: Cascade's headless
// compiler leaves bare package imports external and Node cannot load the
// provider's TypeScript, while a relative path is bundled like project code.
// `--check` fails when any generated stub no longer matches its provider.

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

export const STUB_MARKER = '// Generated by cascade-kit nodes from';

/**
 * The full `export const definition = …;` statement of a node module, or null.
 * Scans the source, skipping strings, template literals and comments, so a
 * brace inside a description does not end the literal early.
 */
export function definitionStatement(source: string): string | null {
  const start = source.search(/export\s+const\s+definition\b/);
  if (start < 0) return null;
  let depth = 0, i = start, seenBrace = false;
  while (i < source.length) {
    const c = source[i], n = source[i + 1];
    if (c === '/' && n === '/') { const e = source.indexOf('\n', i); i = e < 0 ? source.length : e; continue; }
    if (c === '/' && n === '*') { const e = source.indexOf('*/', i + 2); i = e < 0 ? source.length : e + 2; continue; }
    if (c === '"' || c === "'" || c === '`') {
      i++;
      while (i < source.length && source[i] !== c) { if (source[i] === '\\') i++; i++; }
      i++; continue;
    }
    if (c === '{' || c === '[' || c === '(') { depth++; seenBrace = true; }
    else if (c === '}' || c === ']' || c === ')') depth--;
    else if (c === ';' && depth === 0 && seenBrace) return source.slice(start, i + 1);
    i++;
  }
  return null;
}

/** The generated stub for one borrowed node. */
export function stubSource(provider: string, name: string, definition: string): string {
  return [
    `${STUB_MARKER} ${provider}/nodes/${name}. Do not edit: change the provider, then run`,
    `// \`npx cascade-kit nodes ${provider}\` here. \`--check\` reports drift.`,
    `import type { NodeDefinition } from 'cascade/contracts';`,
    '',
    definition,
    '',
    `export { execute } from '../../node_modules/${provider}/nodes/${name}/index';`,
    '',
  ].join('\n');
}

export interface NodesOptions {
  /** the consuming project's root */
  project: string;
  /** the provider's package name, as installed in the project's node_modules */
  provider: string;
  /** node names to borrow; default every node the provider has */
  names?: string[];
  /** compare only, write nothing */
  check?: boolean;
}

export interface NodesResult {
  written: string[];
  unchanged: string[];
  /** with `check`: stubs that are missing or differ from the provider */
  drift: string[];
  /** a local node of the same name that this tool did not write, left alone */
  skipped: string[];
}

/** The provider's node names (directories under `nodes/` with an index.ts). */
export async function providerNodes(providerRoot: string): Promise<string[]> {
  const entries = await readdir(join(providerRoot, 'nodes'), { withFileTypes: true });
  const names: string[] = [];
  for (const e of entries) {
    if (!e.isDirectory()) continue;
    try { await readFile(join(providerRoot, 'nodes', e.name, 'index.ts')); names.push(e.name); } catch { /* not a node */ }
  }
  return names.sort();
}

/** Write (or with `check`, verify) the stubs for a provider's nodes. */
export async function syncNodeStubs(o: NodesOptions): Promise<NodesResult> {
  const providerRoot = join(o.project, 'node_modules', o.provider);
  const names = o.names?.length ? o.names : await providerNodes(providerRoot);
  const result: NodesResult = { written: [], unchanged: [], drift: [], skipped: [] };
  for (const name of names) {
    const source = await readFile(join(providerRoot, 'nodes', name, 'index.ts'), 'utf8');
    const definition = definitionStatement(source);
    if (!definition) throw new Error(`${o.provider}/nodes/${name}/index.ts has no literal \`export const definition\`; only definition-v1 nodes can be borrowed`);
    const want = stubSource(o.provider, name, definition);
    const file = join(o.project, 'nodes', name, 'index.ts');
    let have: string | null = null;
    try { have = await readFile(file, 'utf8'); } catch { /* none yet */ }
    if (have === want) { result.unchanged.push(name); continue; }
    if (have !== null && !have.startsWith(STUB_MARKER)) { result.skipped.push(name); continue; }
    if (o.check) { result.drift.push(name); continue; }
    await mkdir(join(o.project, 'nodes', name), { recursive: true });
    await writeFile(file, want);
    result.written.push(name);
  }
  return result;
}
