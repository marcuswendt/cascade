/**
 * Generates `doc/NODE_REFERENCE.md` — the node catalogue, for agents.
 *
 * Written because of a measurement rather than a hunch. A console-launched
 * Claude, asked to "create a sine oscillator and connect it to the first orb",
 * spent about twenty tool calls working out what nodes exist and what they
 * declare — including reading `src/nodes/Node.ts`, 1,676 lines, twice. The
 * catalogue it needed is 15 definitions and under 8,000 characters.
 *
 * So this is the Meridian move applied to documentation: anything a model
 * recomputes on every task should be an artefact it reads once. Generated at
 * build time rather than hand-maintained, because a hand-written node list is
 * wrong within a fortnight and being confidently wrong is worse than absent.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { builtinNodeRegistrations } from '../packages/runtime/src/builtins/index.ts';
import { coreLibrary } from '../src/nodes/core/library.ts';
import { geoLibrary } from '../src/nodes/geo/library.ts';
import { imageLibrary } from '../src/nodes/image/library.ts';

function portRow(name, port) {
  if (port.kind === 'trigger') return `| \`${name}\` | trigger | | |`;
  const range = [port.min, port.max].every((v) => v !== undefined) ? `${port.min}…${port.max}` : '';
  const dflt = port.default === undefined ? '' : `\`${JSON.stringify(port.default)}\``;
  return `| \`${name}\` | \`${port.type}\` | ${dflt} | ${range} |`;
}

function definitionSection(moduleId, definition) {
  const lines = [`### \`${moduleId}\``, ''];
  const summary = [definition.label, definition.description].filter(Boolean).join(' — ');
  if (summary) lines.push(summary, '');
  lines.push(`Runs on \`${definition.runsOn}\`.`, '');

  for (const [heading, group] of [['Inputs', definition.inputs], ['Props', definition.props], ['Outputs', definition.outputs]]) {
    const entries = Object.entries(group ?? {});
    if (!entries.length) continue;
    lines.push(`**${heading}**`, '', '| name | type | default | range |', '| --- | --- | --- | --- |');
    for (const [name, port] of entries) lines.push(portRow(name, port));
    lines.push('');
  }
  return lines.join('\n');
}

function libraryIndex(library) {
  const lines = [`### ${library.label} — \`cascade.${library.id}.*\``, ''];
  for (const category of library.categories ?? []) {
    const names = (category.nodes ?? [])
      .map((node) => `\`${node.type}\`${node.description ? ` (${node.description})` : ''}`)
      .join(', ');
    if (names) lines.push(`**${category.label}.** ${names}`, '');
  }
  return lines.join('\n');
}

const definitions = [...builtinNodeRegistrations]
  .sort((a, b) => a.moduleId.localeCompare(b.moduleId))
  .map((registration) => definitionSection(registration.moduleId, registration.definition));

const document = `# Node reference

**Generated by \`scripts/build-node-reference.mjs\`. Do not edit — regenerate it.**

Read this before searching the codebase for what a node does. It exists because
that search is expensive and this file is not: the whole catalogue below is under
8,000 characters, and working it out by reading source cost one agent about twenty
tool calls, two of which were the same 1,676-line file.

For the \`.cascade\` document format, expressions, and how to write a node, see
\`AGENTS.md\`. **Note in particular that anything time-based is an expression
rather than a node** — \`sin($T) * 40\` in a parameter — so there is no oscillator
node and none is needed.

## Deterministic nodes, with full declarations

These are definition-v1: their declarations are literal, so what follows is
exact rather than a description.

${definitions.join('\n')}
## Studio node libraries

Class-based nodes, available in Studio. Their parameters are declared in the
class rather than in a literal, so they are listed here by name only — select
one in Studio and read the **Definition** panel for its ports, or open the class
under \`src/nodes/<library>/nodes/\`.

${[coreLibrary, geoLibrary, imageLibrary].map(libraryIndex).join('\n')}## A project's own nodes

Not listed here, because they belong to the project rather than to Cascade. Ask
the running server: \`GET /api/nodes\` returns each module with its \`runsOn\` and
icon, and \`GET /api/nodes/<name>/index.ts\` returns its source.
`;

mkdirSync(resolve('doc'), { recursive: true });
writeFileSync(resolve('doc', 'NODE_REFERENCE.md'), document);
console.log(`[node-reference] ${builtinNodeRegistrations.length} definitions, ${document.length} chars`);
